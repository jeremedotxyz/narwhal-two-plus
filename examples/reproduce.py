"""Reproduce the small synthetic experiment. Run from repository root."""
from dataclasses import asdict
import json
import math
from pathlib import Path
import statistics
from narwhal.config import Config
from narwhal.physics import C0,derived_metrics
from narwhal.pipeline import simulate,reconstruct

cfg=Config.load('config/concept.json')
events=list(simulate(cfg,lines=2,seed=532))
points=[reconstruct(e,cfg) for e in events]
errors=[p.z-5 for p in points if math.isfinite(p.z)]
result={'evidence':'synthetic only; not hardware performance','seed':532,'config':asdict(cfg),
        'records':len(points),'valid':len(errors),'rejected':len(points)-len(errors),
        'z_bias_m':statistics.mean(errors),'z_sample_sigma_m':statistics.stdev(errors),
        'z_rmse_m':math.sqrt(statistics.mean(e*e for e in errors)),
        'timing_only_monostatic_sigma_m':C0*cfg.timing_sigma_ns*1e-9/(2*cfg.n_group),
        'metrics':derived_metrics(cfg)}
out=Path('runs/experiment');out.mkdir(parents=True,exist_ok=True)
(out/'results.json').write_text(json.dumps(result,indent=2)+'\n')
rows=[('Evidence','Synthetic plane; no measured data'),('Seed','532'),('Shots',result['records']),('Valid returns',result['valid']),('Rejected returns',result['rejected']),('Plane Z bias (m)',f"{result['z_bias_m']:.9f}"),('Plane Z sample sigma (m)',f"{result['z_sample_sigma_m']:.9f}"),('Plane Z RMSE (m)',f"{result['z_rmse_m']:.9f}"),('Assumed timing-only sigma (m)',f"{result['timing_only_monostatic_sigma_m']:.9f}")]
md='# Reference numerical results\n\nGenerated by `examples/reproduce.py` with the committed configuration. These results describe synthetic data only. Python pseudorandom implementations can differ across future interpreter versions; exact replay uses the saved raw records.\n\n| Quantity | Value |\n|---|---|\n'+''.join(f'| {k} | {v} |\n' for k,v in rows)
md+='\nTwo repeated stationary scan lines, target plane at Z=5 m, independent 0.1 ns timing noise and 2% assumed dropout. No attenuation-dependent detection model or waveform estimator is included.\n'
(out/'results.md').write_text(md)
print(json.dumps({k:v for k,v in result.items() if k not in ('config','metrics')},indent=2))
